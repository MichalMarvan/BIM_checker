import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, posix, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const output = resolve(root, 'assets/data/precache-manifest.js');
const checkOnly = process.argv.includes('--check');
const extensions = new Set(['.css', '.dtd', '.html', '.ico', '.js', '.json', '.mjs', '.png', '.svg', '.wasm', '.xml', '.xsd']);
const roots = ['assets/css', 'assets/data', 'assets/icons', 'assets/js', 'pages'];
const rootFiles = ['favicon.ico', 'favicon.svg', 'index.html', 'manifest.json'];

function walk(path, target) {
    for (const entry of readdirSync(path, { withFileTypes: true })) {
        const absolute = resolve(path, entry.name);
        if (entry.isDirectory()) walk(absolute, target);
        else target.push(absolute);
    }
}

function webPath(absolute) {
    return './' + relative(root, absolute).split(sep).join('/');
}

const candidates = rootFiles.map(file => resolve(root, file));
for (const folder of roots) walk(resolve(root, folder), candidates);

const runtimeFiles = candidates
    .filter(path => existsSync(path) && statSync(path).isFile())
    .filter(path => extensions.has(posix.extname(webPath(path))))
    .filter(path => path !== output)
    .sort((a, b) => (webPath(a) < webPath(b) ? -1 : (webPath(a) > webPath(b) ? 1 : 0)));
const optionalFiles = runtimeFiles.filter(path => webPath(path).startsWith('./assets/js/vendor/optional/'));
const coreFiles = runtimeFiles.filter(path => !optionalFiles.includes(path));
const hash = createHash('sha256');
for (const path of coreFiles) {
    hash.update(webPath(path));
    hash.update(readFileSync(path));
}
const version = hash.digest('hex').slice(0, 16);
const coreUrls = ['./', ...coreFiles.map(webPath), './assets/data/precache-manifest.js'];
const optionalUrls = optionalFiles.map(webPath);
const generated = `/* SPDX-License-Identifier: AGPL-3.0-or-later */\n` +
    `/* Generated by scripts/generate-precache.mjs. Do not edit manually. */\n` +
    `self.BIM_CHECKER_PRECACHE = Object.freeze(${JSON.stringify({ version, assets: coreUrls, optionalAssets: optionalUrls }, null, 2)});\n`;

if (checkOnly) {
    if (!existsSync(output) || readFileSync(output, 'utf8') !== generated) {
        console.error('Precache manifest is stale. Run: npm run build:pwa');
        process.exitCode = 1;
    } else {
        console.log(`Precache manifest OK: ${coreUrls.length} core assets, ${optionalUrls.length} optional assets (${version}).`);
    }
} else {
    writeFileSync(output, generated);
    console.log(`Generated precache manifest: ${coreUrls.length} core assets, ${optionalUrls.length} optional assets (${version}).`);
}
